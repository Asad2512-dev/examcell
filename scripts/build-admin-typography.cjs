// Keep admin text exactly 3px above the original shared type scale, at each breakpoint.
const fs = require('node:fs');
const postcss = require('postcss');
const root = postcss.parse(fs.readFileSync('resources/css/app.css', 'utf8'));
const result = postcss.root();
const screen = postcss.atRule({name:'media',params:'screen'});
result.append(screen);
root.walkRules(rule => {
  const ancestors=[];
  for(let parent=rule.parent;parent&&parent.type!=='root';parent=parent.parent){
    if(parent.type!=='atrule'||!['media','supports','layer'].includes(parent.name))return;
    if(parent.name==='media'&&/print/.test(parent.params))return;
    ancestors.unshift(parent);
  }
  let size;
  for(const decl of rule.nodes){
    if(decl.type!=='decl')continue;
    if(decl.prop==='font-size')size=decl.value;
    if(decl.prop==='font')size=decl.value.match(/^(\d+(?:\.\d+)?px)(?:\/|\s)/)?.[1]||size;
  }
  if(!size||!/^\d+(?:\.\d+)?px$/.test(size))return;
  const selectors=rule.selectors.filter(selector=>!/(?:auth-|public-|landing-|hero-|preview-|trust-strip|feature-|role-card|role-grid|section-heading|print-|qr-placeholder|verification-|color-swatch)/.test(selector));
  if(!selectors.length)return;
  const scoped=selectors.map(selector=>selector==='body'?'body[data-role="admin"]':selector.startsWith('body ')?selector.replace(/^body /,'body[data-role="admin"] '):`body[data-role="admin"] ${selector}`);
  let target=screen;
  for(const ancestor of ancestors){const wrapper=postcss.atRule({name:ancestor.name,params:ancestor.params});target.append(wrapper);target=wrapper;}
  const output=postcss.rule({selectors:scoped});
  output.append(postcss.decl({prop:'font-size',value:`${parseFloat(size)+3}px`}));
  target.append(output);
});
fs.writeFileSync('resources/css/admin-typography.css','/* Generated by scripts/build-admin-typography.cjs: original shared sizes + 3px. */\n'+result.toString()+'\n');
